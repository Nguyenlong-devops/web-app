const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
const context={window:{}};vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../app/static/js/dates.js'),'utf8'),context);
const d=context.window.DateUI;
assert.equal(d.format('2026-11-19'),'19/11/2026');
assert.equal(d.toISO('05/06/2026'),'2026-06-05');
assert.equal(d.toISO('29/02/2024'),'2024-02-29');
assert.equal(d.toISO(''),'');assert.equal(d.format(''),'');
for(const invalid of ['02/29/2026','29/02/2025','31/04/2026','2026-02-30','1/2/2026','bad']) assert.throws(()=>d.toISO(invalid));
assert.equal(d.dateTime('2026-11-19T20:30:00Z'),'20/11/2026 03:30:00');
assert.equal(d.dateTime('Thu, 19 Nov 2026 20:30:00 GMT'),'20/11/2026 03:30:00');
assert.equal(d.normalize('05/06/2026'),'2026-06-05');
console.log('PASS: DD/MM/YYYY display, unambiguous input, invalid/leap dates, ISO API conversion, Vietnam time at day boundary');
assert.equal(d.warranty('2026-11-18','2026-11-19').status,'expired');
